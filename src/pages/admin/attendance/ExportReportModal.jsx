import React, { useState } from 'react';
import { X, FileSpreadsheet, FileText, Printer, FileDown, Loader2 } from 'lucide-react';
import * as XLSX from 'xlsx';
import { getDetailedReport, getOverview } from '../../../services/attendanceAdminDashboardService';

export default function ExportReportModal({ isOpen, onClose, filters }) {
    const [exporting, setExporting] = useState(false);
    const [error, setError] = useState('');
    const [success, setSuccess] = useState('');

    if (!isOpen) return null; // Don't render if closed

    const handleGenerateExcel = async () => {
        setExporting(true);
        setError('');
        setSuccess('');

        try {
            // 1. Fetch detailed record data + KPI overview
            const [overview, details] = await Promise.all([
                getOverview(filters),
                getDetailedReport(filters)
            ]);

            // 2. Build Excel structure
            const wb = XLSX.utils.book_new();

            // Summary Sheet (A1-based formatting)
            const summaryData = [
                ["UNIVERSITY ATTENDANCE REPORT"],
                ["Generated On:", new Date().toLocaleDateString()],
                ["Total Students:", overview.kpis?.totalStudents || 0],
                ["Total Sessions:", overview.kpis?.sessions || 0],
                ["Overall Attendance:", overview.kpis?.overallAttendance + "%"],
                [],
                ["Filter Context:", JSON.stringify(filters).replace(/[{}"]/g, '')]
            ];
            const summaryWs = XLSX.utils.aoa_to_sheet(summaryData);
            XLSX.utils.book_append_sheet(wb, summaryWs, "Summary");

            // Details Sheet
            if (details && details.length > 0) {
                const ws = XLSX.utils.json_to_sheet(details.map(d => ({
                    Date: d.date,
                    Period: d.period,
                    Subject: d.subject,
                    Code: d.subjectCode,
                    Teacher: d.teacher,
                    Department: d.department,
                    Semester: d.semester,
                    Section: d.section,
                    'Roll Number': d.rollNumber,
                    'Student Name': d.studentName,
                    Status: d.status,
                    Method: d.method,
                    'Marked At': d.markedAt,
                    Remarks: d.remarks
                })));
                XLSX.utils.book_append_sheet(wb, ws, "Attendance Details");
            }

            // Export triggered
            XLSX.writeFile(wb, `Attendance_Report_${new Date().getTime()}.xlsx`);
            setSuccess('Excel Export Generated successfully!');

            setTimeout(() => {
                onClose();
            }, 2000);

        } catch (err) {
            console.error(err);
            setError('Failed to generate Excel report. Please try again or check your network.');
        } finally {
            setExporting(false);
        }
    };

    const handleGenerateWord = async () => {
        setExporting(true);
        setError('');
        setSuccess('');

        try {
            const overview = await getOverview(filters);

            // Build a literal HTML blob containing the core Word content mapping
            const header = "<html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'><head><meta charset='utf-8'><title>Attendance Report</title></head><body>";
            const footer = "</body></html>";

            const content = `
                <div style="font-family: Arial; padding: 20px;">
                    <h1 style="color: #4f46e5;">Attendance Analytics Report</h1>
                    <p><strong>Generated:</strong> ${new Date().toLocaleDateString()}</p>
                    <p><strong>Filters Applied:</strong> ${JSON.stringify(filters).replace(/[{}"]/g, '')}</p>
                    <hr/>
                    <h2>KPI Overview</h2>
                    <ul>
                        <li><strong>Students:</strong> ${overview.kpis?.totalStudents}</li>
                        <li><strong>Sessions Tracked:</strong> ${overview.kpis?.sessions}</li>
                        <li><strong>Overall Attendance:</strong> ${overview.kpis?.overallAttendance}%</li>
                        <li><strong>Total Present Marks:</strong> ${overview.kpis?.present}</li>
                        <li><strong>Total Absent/Leave Marks:</strong> ${overview.kpis?.absent}</li>
                    </ul>
                    <hr/>
                    <h2>System Status Overview</h2>
                    <p>Generated by EduTrack Admins via automatic DOCX export.</p>
                </div>
            `;

            const sourceHTML = header + content + footer;

            const source = 'data:application/vnd.ms-word;charset=utf-8,' + encodeURIComponent(sourceHTML);
            const fileDownload = document.createElement("a");
            fileDownload.href = source;
            fileDownload.download = `Attendance_Summary_${new Date().getTime()}.doc`;
            fileDownload.click();

            setSuccess('Word Doc Downloaded Successfully!');
            setTimeout(() => onClose(), 2000);
        } catch (err) {
            console.error(err);
            setError('Failed to generate document export.');
        } finally {
            setExporting(false);
        }
    };

    const handlePrintOrPDF = () => {
        window.print(); // Using natively supported OS Print-to-PDF / Paper Print styling in CSS
        onClose();
    };

    return (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-sm shadow-2xl">
            <div className="bg-white rounded-2xl w-full max-w-lg shadow-[0_20px_60px_rgba(0,0,0,0.15)] flex flex-col overflow-hidden animate-in fade-in zoom-in-95 duration-200">
                <div className="flex items-center justify-between p-5 border-b border-slate-100">
                    <div>
                        <h2 className="text-xl font-bold text-slate-800">Export Report</h2>
                        <p className="text-sm text-slate-500 mt-1">Select a format to download the filtered dataset.</p>
                    </div>
                    <button onClick={onClose} disabled={exporting} className="p-2 hover:bg-slate-100 rounded-xl text-slate-400 hover:text-slate-700 transition">
                        <X className="w-5 h-5" />
                    </button>
                </div>

                <div className="p-5 overflow-y-auto custom-scrollbar">
                    {/* Active Filter Hint */}
                    <div className="bg-slate-50 px-4 py-3 rounded-xl border border-slate-100 mb-5 pb-4">
                        <p className="text-xs font-semibold text-slate-400 uppercase tracking-widest mb-2">Contextual Data</p>
                        <ul className="text-sm text-slate-600 flex flex-wrap gap-2">
                            <li className="bg-white px-2 py-1 rounded border border-slate-200 flex gap-2 shadow-sm">
                                <span className="font-medium text-slate-400">Section:</span>
                                <span>{filters.section || 'All'}</span>
                            </li>
                            <li className="bg-white px-2 py-1 rounded border border-slate-200 flex gap-2 shadow-sm">
                                <span className="font-medium text-slate-400">Semester:</span>
                                <span>{filters.semester || 'All'}</span>
                            </li>
                            <li className="bg-white px-2 py-1 rounded border border-slate-200 flex gap-2 shadow-sm">
                                <span className="font-medium text-slate-400">Department:</span>
                                <span>{filters.department_id || 'All'}</span>
                            </li>
                        </ul>
                    </div>

                    {error && (
                        <div className="mb-4 bg-rose-50 text-rose-600 text-sm p-3 rounded-lg border border-rose-100">
                            {error}
                        </div>
                    )}
                    {success && (
                        <div className="mb-4 bg-emerald-50 text-emerald-600 font-medium text-sm p-3 rounded-lg border border-emerald-100">
                            {success}
                        </div>
                    )}

                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                        <button
                            onClick={handleGenerateExcel}
                            disabled={exporting}
                            className="flex flex-col items-start gap-2 p-4 rounded-xl border border-slate-200 hover:border-emerald-300 hover:bg-emerald-50 transition-all group disabled:opacity-50 text-left"
                        >
                            <div className="rounded-lg bg-emerald-100 text-emerald-600 p-2 group-hover:scale-110 transition-transform">
                                <FileSpreadsheet className="w-6 h-6" />
                            </div>
                            <div>
                                <h3 className="font-bold text-slate-700">Excel (XLSX)</h3>
                                <p className="text-xs text-slate-500 mt-0.5">Best for raw data analysis</p>
                            </div>
                        </button>

                        <button
                            onClick={handleGenerateWord}
                            disabled={exporting}
                            className="flex flex-col items-start gap-2 p-4 rounded-xl border border-slate-200 hover:border-blue-300 hover:bg-blue-50 transition-all group disabled:opacity-50 text-left"
                        >
                            <div className="rounded-lg bg-blue-100 text-blue-600 p-2 group-hover:scale-110 transition-transform">
                                <FileText className="w-6 h-6" />
                            </div>
                            <div>
                                <h3 className="font-bold text-slate-700">Word (DOC)</h3>
                                <p className="text-xs text-slate-500 mt-0.5">Editable summary template</p>
                            </div>
                        </button>

                        <button
                            onClick={handlePrintOrPDF}
                            disabled={exporting}
                            className="flex flex-col items-start gap-2 p-4 rounded-xl border border-slate-200 hover:border-indigo-300 hover:bg-indigo-50 transition-all group disabled:opacity-50 text-left"
                        >
                            <div className="rounded-lg bg-indigo-100 text-indigo-600 p-2 group-hover:scale-110 transition-transform">
                                <FileDown className="w-6 h-6" />
                            </div>
                            <div>
                                <h3 className="font-bold text-slate-700">PDF</h3>
                                <p className="text-xs text-slate-500 mt-0.5">Official locked document</p>
                            </div>
                        </button>

                        <button
                            onClick={handlePrintOrPDF}
                            disabled={exporting}
                            className="flex flex-col items-start gap-2 p-4 rounded-xl border border-slate-200 hover:border-slate-300 hover:bg-slate-50 transition-all group disabled:opacity-50 text-left"
                        >
                            <div className="rounded-lg bg-slate-100 text-slate-600 p-2 group-hover:scale-110 transition-transform">
                                <Printer className="w-6 h-6" />
                            </div>
                            <div>
                                <h3 className="font-bold text-slate-700">Print</h3>
                                <p className="text-xs text-slate-500 mt-0.5">Direct to printer driver</p>
                            </div>
                        </button>
                    </div>
                </div>

                <div className="p-5 border-t border-slate-100 bg-slate-50/50 flex justify-end">
                    <button
                        onClick={onClose}
                        disabled={exporting}
                        className="px-6 py-2.5 rounded-xl border border-slate-200 text-slate-600 font-medium hover:bg-slate-100 transition-colors disabled:opacity-50"
                    >
                        {exporting ? 'Processing...' : 'Cancel'}
                    </button>
                </div>
            </div>

            {/* Full Screen Loading Overlay while compiling Excel (often fast, but gives UI feedback) */}
            {exporting && (
                <div className="absolute inset-0 bg-white/60 backdrop-blur-[2px] z-[60] flex flex-col items-center justify-center pointer-events-none">
                    <Loader2 className="w-10 h-10 text-indigo-600 animate-spin mb-3" />
                    <p className="font-bold text-slate-800">Generating Report...</p>
                    <p className="text-sm text-slate-500">This may take a few seconds.</p>
                </div>
            )}
        </div>
    );
}
